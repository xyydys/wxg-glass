static const char WXGMenuMorphMetal[] =
    "#include <metal_stdlib>\n"
    "using namespace metal;\n"
    "struct GlassMotionUniforms {\n"
    "    float4 viewport, menu, source, radii, optics, field;\n"
    "    float4 rowsInk, triggerInk, foreground, rowsBlurBox, triggerBlurBox, highlightInk, plateLight;\n"
    "};\n"
    "struct GlassInkBlurUniforms {\n"
    "    float4 rect, region, params, kernelInfo;\n"
    "};\n"
    "struct GlassMotionVertex { float4 position [[position]]; };\n"
    "vertex GlassMotionVertex wxgMenuMorphVertex(uint index [[vertex_id]]) {\n"
    "    GlassMotionVertex out;\n"
    "    out.position = float4(index == 1 ? 3.f : -1.f, index == 2 ? -3.f : 1.f, 0.f, 1.f);\n"
    "    return out;\n"
    "}\n"
    "float2 glassNormal(float2 v) { return v / max(length(v), 0.000001f); }\n"
    "float3 roundedField(float2 p, float4 box, float2 radii) {\n"
    "    float2 r = max(abs(radii), float2(.001f));\n"
    "    float radius = min(r.x, r.y);\n"
    "    float2 inverseAxis = radius / r;\n"
    "    float2 point = (p - box.xy - .5f * box.zw) * inverseAxis;\n"
    "    float2 extent = box.zw * .5f * inverseAxis;\n"
    "    float expandedRadius = radius * 1.5286649465560913f;\n"
    "    float2 curve = clamp(2.8915570351735034f - 2.8915570351735034f * extent / expandedRadius, 0.f, 1.f);\n"
    "    float baseRadius = mix(expandedRadius, radius, max(curve.x, curve.y));\n"
    "    float2 edge = abs(point) - extent;\n"
    "    float2 circle = edge + baseRadius;\n"
    "    float interior = min(max(circle.x, circle.y), 0.f);\n"
    "    float2 z = max((edge + expandedRadius) / expandedRadius, 0.f);\n"
    "    float largest = max(z.x, z.y);\n"
    "    float t = largest > 0.f ? clamp(min(z.x, z.y) / largest, 0.f, 1.f) : 0.f;\n"
    "    float d = length(z);\n"
    "    float shape = ((((-.926054f * t + 3.15601f) * t - 3.64122f) * t + 1.26803f) * t + .268531f) * t * t;\n"
    "    float raw = d + 1.f - 1.f / (1.f - shape * clamp(d, 0.f, 1.f));\n"
    "    float alternate = .3458344340324402f + .6541655659675598f * length(max(1.5286649465560913f * z - .528665f, 0.f));\n"
    "    float weight = clamp((z.y > z.x ? 1.f : -1.f) * (t - 1.f) + .5f, 0.f, 1.f);\n"
    "    float corrected = mix(mix(raw, alternate, curve.x), mix(raw, alternate, curve.y), weight);\n"
    "    float distance = interior + expandedRadius * (corrected - 1.f);\n"
    "    float2 positive = glassNormal(max(circle, 0.f));\n"
    "    if (positive.x + positive.y <= 0.f) positive = circle.x > circle.y ? float2(1.f, 0.f) : float2(0.f, 1.f);\n"
    "    float2 normal = positive * float2(point.x < 0.f ? -1.f : 1.f, point.y < 0.f ? -1.f : 1.f);\n"
    "    float2 oval = glassNormal(float2(point.x, point.y * extent.x / max(extent.y, .001f)));\n"
    "    return float3(distance, glassNormal(mix(normal, oval, .5f)) * inverseAxis);\n"
    "}\n"
    "float3 analyticField(float2 p, constant GlassMotionUniforms &u) {\n"
    "    float3 a = roundedField(p, u.menu, u.radii.xy);\n"
    "    if (min(u.source.z, u.source.w) < .01f) return a;\n"
    "    float3 b = roundedField(p, u.source, u.radii.zz);\n"
    "    float blur = u.radii.w;\n"
    "    if (blur <= .0001f || abs(a.x - b.x) >= blur) return a.x <= b.x ? a : b;\n"
    "    float k = blur * clamp(.5f - .5f * dot(a.yz, b.yz), 0.f, 1.f);\n"
    "    if (k <= .0001f) return a.x <= b.x ? a : b;\n"
    "    float h = clamp(.5f + .5f * (a.x - b.x) / k, 0.f, 1.f);\n"
    "    return float3(mix(a.x, b.x, h) - k * h * (1.f - h), mix(a.yz, b.yz, h));\n"
    "}\n"
    "kernel void wxgMenuMorphField(texture2d<float, access::write> out [[texture(0)]],\n"
    "                            constant GlassMotionUniforms &u [[buffer(0)]], uint2 cell [[thread_position_in_grid]]) {\n"
    "    if (cell.x >= out.get_width() || cell.y >= out.get_height()) return;\n"
    "    float2 p = u.field.xy + float2(cell) * u.field.z;\n"
    "    out.write(float4(analyticField(p, u), 1.f), cell);\n"
    "}\n"
    "kernel void wxgMenuMorphSmooth(texture2d<float, access::sample> in [[texture(0)]],\n"
    "                             texture2d<float, access::write> out [[texture(1)]],\n"
    "                             constant float4 &settings [[buffer(0)]], uint2 cell [[thread_position_in_grid]]) {\n"
    "    if (cell.x >= out.get_width() || cell.y >= out.get_height()) return;\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::nearest);\n"
    "    float2 p = float2(cell) + .5f;\n"
    "    float3 value = in.sample(s, p).xyz;\n"
    "    float2 axis = settings.xy;\n"
    "    float weightSum = 1.f;\n"
    "    for (int i=1; i<=int(settings.w); ++i) {\n"
    "        float weight = exp(-.5f * float(i * i) / (settings.z * settings.z));\n"
    "        float2 offset = float(i) * axis;\n"
    "        value += weight * (in.sample(s, p + offset).xyz + in.sample(s, p - offset).xyz);\n"
    "        weightSum += 2.f * weight;\n"
    "    }\n"
    "    value /= weightSum;\n"
    "    if (axis.y > .5f) value.yz = glassNormal(value.yz);\n"
    "    out.write(float4(value, 1.f), cell);\n"
    "}\n"
    "float3 smoothedFieldSample(texture2d<float> tex, float2 pixel) {\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::linear);\n"
    "    float2 st = pixel - .5f;\n"
    "    float2 base = floor(st);\n"
    "    float2 f = st - base;\n"
    "    float2 f2 = f * f;\n"
    "    float2 f3 = f2 * f;\n"
    "    float2 w0 = (1.f - 3.f * f + 3.f * f2 - f3) * (1.f / 6.f);\n"
    "    float2 w1 = (4.f - 6.f * f2 + 3.f * f3) * (1.f / 6.f);\n"
    "    float2 w2 = (1.f + 3.f * f + 3.f * f2 - 3.f * f3) * (1.f / 6.f);\n"
    "    float2 w3 = f3 * (1.f / 6.f);\n"
    "    float2 g0 = w0 + w1;\n"
    "    float2 g1 = w2 + w3;\n"
    "    float2 h0 = base + .5f + w1 / max(g0, float2(.000001f)) - 1.f;\n"
    "    float2 h1 = base + .5f + w3 / max(g1, float2(.000001f)) + 1.f;\n"
    "    float3 top = tex.sample(s, float2(h0.x, h0.y)).xyz * g0.x + tex.sample(s, float2(h1.x, h0.y)).xyz * g1.x;\n"
    "    float3 bottom = tex.sample(s, float2(h0.x, h1.y)).xyz * g0.x + tex.sample(s, float2(h1.x, h1.y)).xyz * g1.x;\n"
    "    return top * g0.y + bottom * g1.y;\n"
    "}\n"
    "float3 glassField(float2 p, constant GlassMotionUniforms &u, texture2d<float> smoothedField) {\n"
    "    if (u.field.w > .5f) {\n"
    "        float2 pixel = (p - u.field.xy) / u.field.z + .5f;\n"
    "        if (pixel.x >= 1.5f && pixel.y >= 1.5f &&\n"
    "            pixel.x <= u.optics.w - 1.5f && pixel.y <= u.field.w - 1.5f) {\n"
    "            return smoothedFieldSample(smoothedField, pixel);\n"
    "        }\n"
    "    }\n"
    "    return analyticField(p, u);\n"
    "}\n"
    "float4 inkDecal(texture2d<float> ink, float2 p, float4 rect, float lod) {\n"
    "    constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::linear, mip_filter::linear);\n"
    "    float2 uv = (p - rect.xy) / max(rect.zw, float2(.0001f));\n"
    "    if (uv.x <= -.05f || uv.y <= -.05f || uv.x >= 1.05f || uv.y >= 1.05f) return float4(0.f);\n"
    "    float2 size = max(float2(ink.get_width(), ink.get_height()) / exp2(lod), float2(1.f));\n"
    "    float2 decal = clamp(min(uv, 1.f - uv) * size + .5f, 0.f, 1.f);\n"
    "    if (decal.x <= 0.f || decal.y <= 0.f) return float4(0.f);\n"
    "    return ink.sample(s, uv, level(lod)) * (decal.x * decal.y);\n"
    "}\n"
    "kernel void wxgMenuInkBlurH(texture2d<float, access::sample> src [[texture(0)]],\n"
    "                            texture2d<float, access::write> out [[texture(1)]],\n"
    "                            constant GlassInkBlurUniforms &b [[buffer(0)]],\n"
    "                            uint2 tid [[thread_position_in_grid]]) {\n"
    "    if (tid.x >= uint(b.region.z) || tid.y >= uint(b.region.w)) return;\n"
    "    uint2 dst = uint2(b.region.xy) + tid;\n"
    "    if (dst.x >= out.get_width() || dst.y >= out.get_height()) return;\n"
    "    float2 p = (float2(dst) + .5f) * b.params.xy;\n"
    "    int radius = int(b.kernelInfo.y);\n"
    "    float stepPt = b.kernelInfo.x;\n"
    "    float sigma = b.params.z;\n"
    "    float lod = b.kernelInfo.z;\n"
    "    float4 sum = inkDecal(src, p, b.rect, lod);\n"
    "    float weightSum = 1.f;\n"
    "    if (radius > 0 && sigma > .01f) {\n"
    "        float inv2Sigma2 = -.5f / (sigma * sigma);\n"
    "        for (int i = 1; i <= radius; ++i) {\n"
    "            float d = float(i) * stepPt;\n"
    "            float w = exp(d * d * inv2Sigma2);\n"
    "            sum += w * (inkDecal(src, float2(p.x + d, p.y), b.rect, lod) +\n"
    "                        inkDecal(src, float2(p.x - d, p.y), b.rect, lod));\n"
    "            weightSum += 2.f * w;\n"
    "        }\n"
    "    }\n"
    "    out.write((sum / weightSum) * b.params.w, dst);\n"
    "}\n"
    "float4 scratchSample(texture2d<float, access::sample> src, float2 px, float2 yLimits) {\n"
    "    if (px.y <= yLimits.x || px.y >= yLimits.y) return float4(0.f);\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::linear);\n"
    "    float edge = clamp(min(px.y - yLimits.x, yLimits.y - px.y), 0.f, 1.f);\n"
    "    float sampleY = clamp(px.y, yLimits.x + .5f, max(yLimits.x + .5f, yLimits.y - .5f));\n"
    "    return src.sample(s, float2(px.x, sampleY)) * edge;\n"
    "}\n"
    "kernel void wxgMenuInkBlurV(texture2d<float, access::sample> src [[texture(0)]],\n"
    "                            texture2d<float, access::write> out [[texture(1)]],\n"
    "                            constant GlassInkBlurUniforms &b [[buffer(0)]],\n"
    "                            uint2 tid [[thread_position_in_grid]]) {\n"
    "    if (tid.x >= uint(b.region.z) || tid.y >= uint(b.region.w)) return;\n"
    "    uint2 dst = uint2(b.region.xy) + tid;\n"
    "    if (dst.x >= out.get_width() || dst.y >= out.get_height()) return;\n"
    "    float2 px = float2(dst) + .5f;\n"
    "    int radius = int(b.kernelInfo.y);\n"
    "    float stepPt = b.kernelInfo.x;\n"
    "    float stepPx = stepPt / max(b.params.y, .0001f);\n"
    "    float sigma = b.params.z;\n"
    "    float2 yLimits = b.kernelInfo.zw;\n"
    "    float4 sum = scratchSample(src, px, yLimits);\n"
    "    float weightSum = 1.f;\n"
    "    if (radius > 0 && sigma > .01f) {\n"
    "        float inv2Sigma2 = -.5f / (sigma * sigma);\n"
    "        for (int i = 1; i <= radius; ++i) {\n"
    "            float dPt = float(i) * stepPt;\n"
    "            float dPx = float(i) * stepPx;\n"
    "            float w = exp(dPt * dPt * inv2Sigma2);\n"
    "            sum += w * (scratchSample(src, float2(px.x, px.y + dPx), yLimits) +\n"
    "                        scratchSample(src, float2(px.x, px.y - dPx), yLimits));\n"
    "            weightSum += 2.f * w;\n"
    "        }\n"
    "    }\n"
    "    out.write(sum / weightSum, dst);\n"
    "}\n"
    "float4 preblurredInkAt(texture2d<float> blurred, float2 p, float4 pxBox, float2 viewportXY) {\n"
    "    float2 px = p / max(viewportXY, float2(.0001f));\n"
    "    if (px.x <= pxBox.x || px.y <= pxBox.y || px.x >= pxBox.z || px.y >= pxBox.w) return float4(0.f);\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::linear);\n"
    "    float2 fade = clamp(min(px - pxBox.xy, pxBox.zw - px), 0.f, 1.f);\n"
    "    float2 clampedPx = clamp(px, pxBox.xy + .5f, max(pxBox.xy + .5f, pxBox.zw - .5f));\n"
    "    return blurred.sample(s, clampedPx) * (fade.x * fade.y);\n"
    "}\n"
    "float4 foregroundAt(float2 p, float3 field, float aa, constant GlassMotionUniforms &u,\n"
    "                    texture2d<float> rows, texture2d<float> trigger,\n"
    "                    texture2d<float> rowsBlurTex, texture2d<float> triggerBlurTex) {\n"
    "    float inside = -field.x;\n"
    "    float coverage = inside < -5.f ? 0.f : clamp(inside / aa + .5f, 0.f, 1.f);\n"
    "    if (coverage < .00392157f) return float4(0.f);\n"
    "    float2 samplePoint = p;\n"
    "    if (u.optics.x > .0001f && abs(u.optics.y) > .0001f) {\n"
    "        float t = clamp(inside / u.optics.x, 0.f, 1.f);\n"
    "        float profile = sqrt(max(1.f - (1.f - t) * (1.f - t), 0.f));\n"
    "        float innerAA = clamp((u.optics.x - inside) / aa + .5f, 0.f, 1.f);\n"
    "        samplePoint = p + u.optics.y * field.yz * (1.f - profile) * innerAA;\n"
    "    }\n"
    "    float4 source = float4(0.f);\n"
    "    if (u.foreground.y > .001f) {\n"
    "        source = ((u.triggerBlurBox.z > u.triggerBlurBox.x)\n"
    "            ? preblurredInkAt(triggerBlurTex, samplePoint, u.triggerBlurBox, u.viewport.xy)\n"
    "            : inkDecal(trigger, samplePoint, u.triggerInk, 0.f)) * u.foreground.y;\n"
    "    }\n"
    "    if (u.foreground.w > .001f) {\n"
    "        float4 plate = u.highlightInk;\n"
    "        float2 scale = max(u.plateLight.yz, float2(.0001f));\n"
    "        float2 local = (samplePoint - plate.xy) / scale;\n"
    "        plate = float4(0.f, 0.f, plate.zw / scale);\n"
    "        float radius = min(plate.z, plate.w) * .5f;\n"
    "        float distance = roundedField(local, plate, float2(radius)).x * min(scale.x, scale.y);\n"
    "        float soft = max(aa, 1.8f * u.foreground.z);\n"
    "        float mask = clamp(.5f - distance / soft, 0.f, 1.f);\n"
    "        bool dark = u.optics.z > .5f;\n"
    "        float lightX = clamp(u.plateLight.x, 0.f, plate.z);\n"
    "        float shine = saturate(1.f - length(local - float2(lightX, plate.w * .5f)) / max(.01f, .62f * plate.z));\n"
    "        float opacity = u.foreground.w * mask * (dark ? .155f + .03f * shine : .09f);\n"
    "        float3 tint = dark ? float3(.92156863f, .92156863f, .96078431f) : float3(.23529412f, .23529412f, .26274510f);\n"
    "        source = float4(tint * opacity, opacity) + source * (1.f - opacity);\n"
    "    }\n"
    "    float4 content = float4(0.f);\n"
    "    if (u.foreground.x > .001f) {\n"
    "        content = ((u.rowsBlurBox.z > u.rowsBlurBox.x)\n"
    "            ? preblurredInkAt(rowsBlurTex, samplePoint, u.rowsBlurBox, u.viewport.xy)\n"
    "            : inkDecal(rows, samplePoint, u.rowsInk, 0.f)) * u.foreground.x;\n"
    "    }\n"
    "    return (content + source * (1.f - content.a)) * coverage;\n"
    "}\n"
    "fragment float4 wxgMenuMorphFragment(GlassMotionVertex vertexOut [[stage_in]], constant GlassMotionUniforms &u [[buffer(0)]],\n"
    "                                    texture2d<float> smoothedField [[texture(0)]],\n"
    "                                    texture2d<float> rows [[texture(1)]], texture2d<float> trigger [[texture(2)]],\n"
    "                                    texture2d<float> rowsBlurTex [[texture(3)]], texture2d<float> triggerBlurTex [[texture(4)]]) {\n"
    "    if (max(u.foreground.x, u.foreground.y) <= .001f && u.foreground.w <= .001f) return float4(0.f);\n"
    "    float2 p = vertexOut.position.xy * u.viewport.xy;\n"
    "    float3 field = glassField(p, u, smoothedField);\n"
    "    float aa = max((abs(field.y) + abs(field.z)) * u.viewport.z, .0001f);\n"
    "    return foregroundAt(p, field, aa, u, rows, trigger, rowsBlurTex, triggerBlurTex);\n"
    "}\n";

