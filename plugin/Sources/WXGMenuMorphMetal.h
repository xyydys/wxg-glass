static const char WXGMenuMorphMetal[] =
    "#include <metal_stdlib>\n"
    "using namespace metal;\n"
    "struct GlassMotionUniforms {\n"
    "    float4 viewport, menu, source, radii, optics, field;\n"
    "    float4 rowsInk, triggerInk, foreground, inkBlur, highlightInk, plateLight;\n"
    "};\n"
    "struct GlassMotionVertex { float4 position [[position]]; };\n"
    "vertex GlassMotionVertex wxgMenuMorphVertex(uint index [[vertex_id]]) {\n"
    "    GlassMotionVertex out;\n"
    "    out.position = float4(index == 1 ? 3.f : -1.f, index == 2 ? -3.f : 1.f, 0.f, 1.f);\n"
    "    return out;\n"
    "}\n"
    "float2 glassNormal(float2 v) { return v / max(length(v), 0.000001f); }\n"
    "float3 roundedField(float2 p, float4 box, float2 radii) {\n"
    "    float2 r = max(abs(radii), float2(.001f));\n"
    "    float radius = min(r.x, r.y);\n"
    "    float2 inverseAxis = radius / r;\n"
    "    float2 point = (p - box.xy - .5f * box.zw) * inverseAxis;\n"
    "    float2 extent = box.zw * .5f * inverseAxis;\n"
    "    float expandedRadius = radius * 1.5286649465560913f;\n"
    "    float2 curve = clamp(2.8915570351735034f - 2.8915570351735034f * extent / expandedRadius, 0.f, 1.f);\n"
    "    float baseRadius = mix(expandedRadius, radius, max(curve.x, curve.y));\n"
    "    float2 edge = abs(point) - extent;\n"
    "    float2 circle = edge + baseRadius;\n"
    "    float interior = min(max(circle.x, circle.y), 0.f);\n"
    "    float2 z = max((edge + expandedRadius) / expandedRadius, 0.f);\n"
    "    float largest = max(z.x, z.y);\n"
    "    float t = largest > 0.f ? clamp(min(z.x, z.y) / largest, 0.f, 1.f) : 0.f;\n"
    "    float d = length(z);\n"
    "    float shape = ((((-.926054f * t + 3.15601f) * t - 3.64122f) * t + 1.26803f) * t + .268531f) * t * t;\n"
    "    float raw = d + 1.f - 1.f / (1.f - shape * clamp(d, 0.f, 1.f));\n"
    "    float alternate = .3458344340324402f + .6541655659675598f * length(max(1.5286649465560913f * z - .528665f, 0.f));\n"
    "    float weight = clamp((z.y > z.x ? 1.f : -1.f) * (t - 1.f) + .5f, 0.f, 1.f);\n"
    "    float corrected = mix(mix(raw, alternate, curve.x), mix(raw, alternate, curve.y), weight);\n"
    "    float distance = interior + expandedRadius * (corrected - 1.f);\n"
    "    float2 positive = glassNormal(max(circle, 0.f));\n"
    "    if (positive.x + positive.y <= 0.f) positive = circle.x > circle.y ? float2(1.f, 0.f) : float2(0.f, 1.f);\n"
    "    float2 normal = positive * float2(point.x < 0.f ? -1.f : 1.f, point.y < 0.f ? -1.f : 1.f);\n"
    "    float2 oval = glassNormal(float2(point.x, point.y * extent.x / max(extent.y, .001f)));\n"
    "    return float3(distance, glassNormal(mix(normal, oval, .5f)) * inverseAxis);\n"
    "}\n"
    "float3 analyticField(float2 p, constant GlassMotionUniforms &u) {\n"
    "    float3 a = roundedField(p, u.menu, u.radii.xy);\n"
    "    if (min(u.source.z, u.source.w) < .01f) return a;\n"
    "    float3 b = roundedField(p, u.source, u.radii.zz);\n"
    "    float k = u.radii.w * clamp(.5f - .5f * dot(a.yz, b.yz), 0.f, 1.f);\n"
    "    if (k < .0001f) return a.x < b.x ? a : b;\n"
    "    float h = clamp(.5f + .5f * (a.x - b.x) / k, 0.f, 1.f);\n"
    "    return float3(mix(a.x, b.x, h) - k * h * (1.f - h), mix(a.yz, b.yz, h));\n"
    "}\n"
    "kernel void wxgMenuMorphField(texture2d<float, access::write> out [[texture(0)]],\n"
    "                            constant GlassMotionUniforms &u [[buffer(0)]], uint2 cell [[thread_position_in_grid]]) {\n"
    "    if (cell.x >= out.get_width() || cell.y >= out.get_height()) return;\n"
    "    float2 p = u.field.xy + float2(cell) * u.field.z;\n"
    "    out.write(float4(analyticField(p, u), 1.f), cell);\n"
    "}\n"
    "kernel void wxgMenuMorphSmooth(texture2d<float, access::sample> in [[texture(0)]],\n"
    "                             texture2d<float, access::write> out [[texture(1)]],\n"
    "                             constant float4 &settings [[buffer(0)]], uint2 cell [[thread_position_in_grid]]) {\n"
    "    if (cell.x >= out.get_width() || cell.y >= out.get_height()) return;\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::nearest);\n"
    "    float2 p = float2(cell) + .5f;\n"
    "    float3 value = in.sample(s, p).xyz;\n"
    "    float2 axis = settings.xy;\n"
    "    float weightSum = 1.f;\n"
    "    for (int i=1; i<=int(settings.w); ++i) {\n"
    "        float weight = exp(-.5f * float(i * i) / (settings.z * settings.z));\n"
    "        float2 offset = float(i) * axis;\n"
    "        value += weight * (in.sample(s, p + offset).xyz + in.sample(s, p - offset).xyz);\n"
    "        weightSum += 2.f * weight;\n"
    "    }\n"
    "    value /= weightSum;\n"
    "    if (axis.y > .5f) value.yz = glassNormal(value.yz);\n"
    "    out.write(float4(value, 1.f), cell);\n"
    "}\n"
    "float3 glassField(float2 p, constant GlassMotionUniforms &u, texture2d<float> smoothedField) {\n"
    "    if (u.field.w < .5f) return analyticField(p, u);\n"
    "    constexpr sampler s(coord::pixel, address::clamp_to_edge, filter::linear);\n"
    "    float2 cell = (p - u.field.xy) / u.field.z + .5f;\n"
    "    return smoothedField.sample(s, cell).xyz;\n"
    "}\n"
    "float4 inkAt(texture2d<float> ink, float2 p, float4 rect, float lod) {\n"
    "    constexpr sampler s(coord::normalized, address::clamp_to_edge, filter::linear, mip_filter::linear);\n"
    "    float2 uv = (p - rect.xy) / rect.zw;\n"
    "    float2 size = float2(ink.get_width(), ink.get_height());\n"
    "    float2 decal = clamp(min(uv, 1.f - uv) * size / exp2(lod) + .5f, 0.f, 1.f);\n"
    "    return ink.sample(s, uv, level(lod)) * decal.x * decal.y;\n"
    "}\n"
    "float4 blurredInk(texture2d<float> ink, float2 p, float4 rect, float2 blur, float opacity) {\n"
    "    if (opacity <= .001f || min(rect.z, rect.w) <= .001f) return float4(0.f);\n"
    "    float2 outside = abs(p - (rect.xy + .5f * rect.zw)) - .5f * rect.zw;\n"
    "    if (outside.x > blur.x * 2.f + 1.f || outside.y > blur.y * 2.f + 1.f) return float4(0.f);\n"
    "    if (max(blur.x, blur.y) < .01f) return inkAt(ink, p, rect, 0.f) * opacity;\n"
    "    float2 pixelScale = float2(ink.get_width(), ink.get_height()) / rect.zw;\n"
    "    float2 sigma = blur * pixelScale;\n"
    "    float common = min(sigma.x, sigma.y);\n"
    "    float lod = clamp(log2(max(1.f, 3.46410162f * common)), 0.f, float(ink.get_num_mip_levels() - 1));\n"
    "    float2 extra = max(sigma * sigma - common * common, 0.f);\n"
    "    float2 step = float2(sqrt(extra.x), sqrt(extra.y)) / pixelScale;\n"
    "    if (length(step) < .04f) return inkAt(ink, p, rect, lod) * opacity;\n"
    "    float4 color = inkAt(ink, p, rect, lod) * .40f;\n"
    "    color += (inkAt(ink, p + step, rect, lod) + inkAt(ink, p - step, rect, lod)) * .24f;\n"
    "    color += (inkAt(ink, p + 2.f * step, rect, lod) + inkAt(ink, p - 2.f * step, rect, lod)) * .06f;\n"
    "    return color * opacity;\n"
    "}\n"
    "float4 foregroundAt(float2 p, float3 field, float aa, constant GlassMotionUniforms &u,\n"
    "                    texture2d<float> rows, texture2d<float> trigger) {\n"
    "    float depth = -field.x;\n"
    "    float t = clamp(depth / max(u.optics.x, .0001f), 0.f, 1.f);\n"
    "    float profile = sqrt(max(1.f - (1.f - t) * (1.f - t), 0.f));\n"
    "    float innerAA = clamp((u.optics.x - depth) / aa + .5f, 0.f, 1.f);\n"
    "    float2 samplePoint = p + u.optics.y * field.yz * (1.f - profile) * innerAA;\n"
    "    float portalVariance = u.foreground.z * u.foreground.z;\n"
    "    float4 variance = u.inkBlur * u.inkBlur + portalVariance;\n"
    "    float4 blur = float4(sqrt(variance.x), sqrt(variance.y), sqrt(variance.z), sqrt(variance.w));\n"
    "    float4 source = blurredInk(trigger, samplePoint, u.triggerInk, blur.zw, u.foreground.y);\n"
    "    if (u.foreground.w > .001f) {\n"
    "        float4 plate = u.highlightInk;\n"
    "        float2 scale = max(u.plateLight.yz, .0001f);\n"
    "        float2 local = (samplePoint - plate.xy) / scale;\n"
    "        plate = float4(0.f, 0.f, plate.zw / scale);\n"
    "        float radius = min(plate.z, plate.w) * .5f;\n"
    "        float distance = roundedField(local, plate, float2(radius)).x * min(scale.x, scale.y);\n"
    "        float mask = clamp(.5f - distance / max(aa, u.foreground.z), 0.f, 1.f);\n"
    "        bool dark = u.optics.z > .5f;\n"
    "        float lightX = clamp(u.plateLight.x, 0.f, plate.z);\n"
    "        float shine = saturate(1.f - length(local - float2(lightX, plate.w * .5f)) / max(.01f, .62f * plate.z));\n"
    "        float opacity = u.foreground.w * mask * (dark ? .155f + .03f * shine : .09f);\n"
    "        float3 tint = dark ? float3(.92156863f, .92156863f, .96078431f) : float3(.23529412f, .23529412f, .26274510f);\n"
    "        source = float4(tint * opacity, opacity) + source * (1.f - opacity);\n"
    "    }\n"
    "    float4 content = blurredInk(rows, samplePoint, u.rowsInk, blur.xy, u.foreground.x);\n"
    "    return content + source * (1.f - content.a);\n"
    "}\n"
    "fragment float4 wxgMenuMorphFragment(GlassMotionVertex vertexOut [[stage_in]], constant GlassMotionUniforms &u [[buffer(0)]],\n"
    "                                    texture2d<float> smoothedField [[texture(0)]],\n"
    "                                    texture2d<float> rows [[texture(1)]], texture2d<float> trigger [[texture(2)]]) {\n"
    "    float2 p = vertexOut.position.xy * u.viewport.xy;\n"
    "    float3 field = glassField(p, u, smoothedField);\n"
    "    float aa = max((abs(field.y) + abs(field.z)) * u.viewport.z, .001f);\n"
    "    if (max(u.foreground.x, u.foreground.y) <= .001f) return float4(0.f);\n"
    "    return foregroundAt(p, field, aa, u, rows, trigger);\n"
    "}\n";

#endif
